const sampul = document.getElementById("sampul");
const website = document.getElementById("website");
const halamanAwal = document.getElementById("halaman-awal");
const pembacaSurat = document.getElementById("pembaca-surat");
const tombolMasuk = document.getElementById("tombol-masuk");
const tombolBukaSurat = document.getElementById("tombol-buka-surat");
const tombolSebelumnya = document.getElementById("tombol-sebelumnya");
const tombolOtomatis = document.getElementById("tombol-otomatis");
const tombolBerikutnya = document.getElementById("tombol-berikutnya");
const nomorHalaman = document.getElementById("nomor-halaman");
const teksHalaman = document.getElementById("teks-halaman");

let indeksHalaman = 0;
let otomatisAktif = true;
let sedangMengetik = false;
let generasiHalaman = 0;
let timerOtomatis = null;

function jeda(ms) {
  return new Promise((selesai) => window.setTimeout(selesai, ms));
}

function perbaruiTombolOtomatis() {
  tombolOtomatis.textContent = otomatisAktif
    ? "Jeda otomatis"
    : "Lanjut otomatis";
}

async function tampilkanHalaman(indeks) {
  window.clearTimeout(timerOtomatis);

  const generasiIni = ++generasiHalaman;
  indeksHalaman = indeks;
  sedangMengetik = true;

  nomorHalaman.textContent =
    `Halaman ${indeks + 1} dari ${halamanSurat.length}`;
  teksHalaman.replaceChildren();
  tombolSebelumnya.disabled = indeks === 0;
  tombolBerikutnya.disabled = false;

  for (const kalimat of halamanSurat[indeks]) {
    if (generasiIni !== generasiHalaman) return;

    const paragraf = document.createElement("p");
    teksHalaman.appendChild(paragraf);

    for (const huruf of kalimat) {
      if (generasiIni !== generasiHalaman) return;
      paragraf.textContent += huruf;
      await jeda(20);
    }

    await jeda(220);
  }

  if (generasiIni !== generasiHalaman) return;

  sedangMengetik = false;

  if (indeks === halamanSurat.length - 1) {
    otomatisAktif = false;
    perbaruiTombolOtomatis();
    tombolBerikutnya.textContent = "Kembali ke halaman awal";
    return;
  }

  tombolBerikutnya.textContent = "Berikutnya →";

  if (otomatisAktif) {
    timerOtomatis = window.setTimeout(() => {
      tampilkanHalaman(indeksHalaman + 1);
    }, 2200);
  }
}

tombolMasuk.addEventListener("click", () => {
  sampul.classList.add("tersembunyi");
  website.classList.remove("tersembunyi");
  halamanAwal.classList.remove("tersembunyi");
  pembacaSurat.classList.add("tersembunyi");
  window.scrollTo({ top: 0, behavior: "smooth" });
});

tombolBukaSurat.addEventListener("click", () => {
  halamanAwal.classList.add("tersembunyi");
  pembacaSurat.classList.remove("tersembunyi");
  otomatisAktif = true;
  perbaruiTombolOtomatis();
  window.scrollTo({ top: 0, behavior: "smooth" });
  tampilkanHalaman(0);
});

tombolOtomatis.addEventListener("click", () => {
  otomatisAktif = !otomatisAktif;
  perbaruiTombolOtomatis();

  if (!otomatisAktif) {
    window.clearTimeout(timerOtomatis);
    return;
  }

  if (!sedangMengetik && indeksHalaman < halamanSurat.length - 1) {
    timerOtomatis = window.setTimeout(() => {
      tampilkanHalaman(indeksHalaman + 1);
    }, 900);
  }
});

tombolSebelumnya.addEventListener("click", () => {
  if (indeksHalaman > 0) {
    tampilkanHalaman(indeksHalaman - 1);
  }
});

tombolBerikutnya.addEventListener("click", () => {
  if (indeksHalaman === halamanSurat.length - 1) {
    window.clearTimeout(timerOtomatis);
    generasiHalaman++;
    pembacaSurat.classList.add("tersembunyi");
    halamanAwal.classList.remove("tersembunyi");
    window.scrollTo({ top: 0, behavior: "smooth" });
    return;
  }

  tampilkanHalaman(indeksHalaman + 1);
});

