/* Animasi langit: bintang berkelip, bulan, awan, dan kunang-kunang. */
const kanvas = document.getElementById("langit");
const ctx = kanvas.getContext("2d");

let lebar = 0;
let tinggi = 0;
let bintang = [];

function aturUkuranKanvas() {
  const rasio = Math.min(window.devicePixelRatio || 1, 2);

  lebar = window.innerWidth;
  tinggi = window.innerHeight;
  kanvas.width = lebar * rasio;
  kanvas.height = tinggi * rasio;
  ctx.setTransform(rasio, 0, 0, rasio, 0, 0);

  bintang = Array.from({ length: 75 }, () => ({
    x: Math.random() * lebar,
    y: Math.random() * tinggi * 0.75,
    ukuran: Math.random() * 1.7 + 0.5,
    fase: Math.random() * Math.PI * 2
  }));
}

function gambarAwan(x, y, skala) {
  ctx.fillStyle = "rgba(220, 197, 222, 0.14)";
  ctx.beginPath();
  ctx.ellipse(x, y, 48 * skala, 13 * skala, 0, 0, Math.PI * 2);
  ctx.ellipse(x - 24 * skala, y + 2 * skala, 22 * skala, 11 * skala, 0, 0, Math.PI * 2);
  ctx.ellipse(x + 22 * skala, y + skala, 26 * skala, 12 * skala, 0, 0, Math.PI * 2);
  ctx.fill();
}

function gambarLangit(waktu = 0) {
  ctx.clearRect(0, 0, lebar, tinggi);

  for (const titik of bintang) {
    const kilau = (Math.sin(waktu * 0.0015 + titik.fase) + 1) / 2;
    ctx.globalAlpha = 0.3 + kilau * 0.7;
    ctx.fillStyle = "#fff2f5";
    ctx.beginPath();
    ctx.arc(titik.x, titik.y, titik.ukuran, 0, Math.PI * 2);
    ctx.fill();
  }

  ctx.globalAlpha = 1;
  ctx.beginPath();
  ctx.arc(lebar * 0.8, tinggi * 0.2, 30, 0, Math.PI * 2);
  ctx.fillStyle = "#fff0d6";
  ctx.shadowColor = "#ffe8c477";
  ctx.shadowBlur = 26;
  ctx.fill();
  ctx.shadowBlur = 0;

  const awanX = (waktu * 0.012) % (lebar + 180) - 90;
  gambarAwan(awanX, tinggi * 0.37, 1);
  gambarAwan((awanX + lebar * 0.55) % (lebar + 180) - 90, tinggi * 0.48, 0.75);

  for (let i = 0; i < 9; i++) {
    const x =
      (i * 137 + waktu * (0.012 + (i % 3) * 0.004)) % lebar;
    const y =
      tinggi * (0.58 + (i % 4) * 0.08) +
      Math.sin(waktu * 0.001 + i) * 10;

    ctx.globalAlpha = 0.4 + (Math.sin(waktu * 0.003 + i) + 1) * 0.25;
    ctx.fillStyle = "#ffe6a8";
    ctx.shadowColor = "#ffe6a8";
    ctx.shadowBlur = 12;
    ctx.beginPath();
    ctx.arc(x, y, 2, 0, Math.PI * 2);
    ctx.fill();
  }

  ctx.globalAlpha = 1;
  ctx.shadowBlur = 0;
  window.requestAnimationFrame(gambarLangit);
}

window.addEventListener("resize", aturUkuranKanvas);
aturUkuranKanvas();
window.requestAnimationFrame(gambarLangit);